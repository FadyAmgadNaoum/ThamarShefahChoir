/**
 * Normalizes an individual Arabic token for fuzzy matching:
 * - Strips diacritics & tatweel
 * - Normalizes alef, taa marbouta, yaa
 * - Safely strips prepositions ('بال', 'ب', 'ال', 'و')
 */
export function normalizeToken(token: string): string {
  let t = token
    .toLowerCase()
    .replace(/[ًٌٍَُِّْـ]/g, "")
    .replace(/[أإآ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .trim();

  // Strip conjunction 'و' if word length > 3 (e.g. والعذراء -> العذراء)
  if (t.startsWith("و") && t.length > 3) {
    t = t.substring(1);
  }
  // Strip 'بال' (e.g. بالزيتون -> زيتون)
  if (t.startsWith("بال") && t.length > 4) {
    t = t.substring(3);
  }
  // Strip 'ب' if followed by place name (e.g. بمسرة -> مسرة, بشبرا -> شبرا)
  else if (
    t.startsWith("ب") &&
    t.length > 4 &&
    !["بابا", "برباره", "بيشوي", "بطرس", "بولس", "بني", "بولاق"].some((w) => t.startsWith(w))
  ) {
    t = t.substring(1);
  }
  // Strip 'ال' (e.g. العذراء -> عذراء)
  if (t.startsWith("ال") && t.length > 3) {
    t = t.substring(2);
  }
  return t;
}

/**
 * Normalizes full Arabic string by splitting into tokens and normalizing each
 */
export function normalizeArabic(text: string): string {
  if (!text) return "";
  return text
    .split(/\s+/)
    .map((w) => normalizeToken(w))
    .filter(Boolean)
    .join(" ");
}

// Stop words that are generic when more specific tokens exist
const GENERIC_CHURCH_TOKENS = new Set([
  "كنيسه",
  "قديس",
  "قديسه",
  "شهيد",
  "عظيم",
  "قاعه",
  "دير",
  "سيده",
]);

/**
 * Searches local registry of Egyptian Coptic Churches with high-precision fuzzy matching
 */
export function searchLocalChurches(query: string): ChurchRecord[] {
  const qTokens = query
    .split(/\s+/)
    .map(normalizeToken)
    .filter((t) => t.length > 1);

  if (qTokens.length === 0) return [];

  const meaningfulTokens = qTokens.filter((t) => !GENERIC_CHURCH_TOKENS.has(t));
  const activeTokens = meaningfulTokens.length > 0 ? meaningfulTokens : qTokens;

  const matches: { church: ChurchRecord; score: number }[] = [];

  for (const church of EGYPTIAN_CHURCHES_REGISTRY) {
    const churchWords = `${church.name} ${church.aliases.join(" ")} ${church.area} ${church.city}`
      .split(/\s+/)
      .map(normalizeToken);

    const churchTokensSet = new Set(churchWords);

    let score = 0;

    // Check direct aliases
    for (const alias of church.aliases) {
      if (
        alias.toLowerCase().includes(query.toLowerCase()) ||
        query.toLowerCase().includes(alias.toLowerCase())
      ) {
        score += 50;
      }
    }

    let matchedTokenCount = 0;
    for (const token of activeTokens) {
      if (churchTokensSet.has(token)) {
        matchedTokenCount += 1;
        score += 20;
      } else {
        const partial = churchWords.some((cw) => cw.includes(token) || token.includes(cw));
        if (partial) {
          matchedTokenCount += 0.8;
          score += 10;
        }
      }
    }

    // Require high token coverage
    if (matchedTokenCount >= activeTokens.length * 0.75) {
      matches.push({ church, score });
    }
  }

  matches.sort((a, b) => b.score - a.score);

  return matches.map((m) => m.church);
}

